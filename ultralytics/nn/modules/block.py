class ESSamp_v2(nn.Module):
    """
    ESSamp 优化版: 先融合亚像素，后感知空间
    计算量更低，对高频边缘的捕捉更符合物理直觉
    """

    def __init__(self, c1, c2, k=3):
        super().__init__()
        self.unshuffle = nn.PixelUnshuffle(2)
        c_unshuffled = c1 * 4

        # 第一步：Pointwise Conv (亚像素早期融合)
        # 作用：将 PixelUnshuffle 折叠到通道中的 4 个相邻像素立刻进行物理混合
        # 将维度从 c1*4 直接平滑降维/升维到目标通道数 c2
        self.pw = nn.Conv2d(c_unshuffled, c2, kernel_size=1, stride=1, padding=0, bias=False)
        self.bn1 = nn.BatchNorm2d(c2)
        self.act1 = nn.SiLU(inplace=True)  # 建议换成RT-DETR/YOLO系标配的 SiLU

        # 第二步：Depthwise Conv (空间拓扑感知)
        # 作用：在融合完毕的高频特征上，进行 3x3 的局部空间感受野扩展
        self.dw = nn.Conv2d(c2, c2, kernel_size=k, stride=1, padding=autopad(k), groups=c2, bias=False)
        self.bn2 = nn.BatchNorm2d(c2)
        self.act2 = nn.SiLU(inplace=True)

    def forward(self, x):
        x = self.unshuffle(x)
        # 数据流：打散 -> 立刻融合 (1x1) -> 空间提炼 (3x3 DW)
        x = self.act1(self.bn1(self.pw(x)))
        x = self.act2(self.bn2(self.dw(x)))
        return x


class ASFF(nn.Module):
    def __init__(self, c1, c2, level=0):
        super().__init__()
        self.level = level
        self.dim = c1
        self.inter_dim = self.dim[self.level]

        self.weight_level_0 = Conv(self.inter_dim, 1, 1, 1)
        self.weight_level_1 = Conv(self.inter_dim, 1, 1, 1)
        self.weight_level_2 = Conv(self.inter_dim, 1, 1, 1)

        self.compress_level_0 = Conv(self.dim[0], self.inter_dim, 1, 1) if self.dim[0] != self.inter_dim else nn.Identity()
        self.compress_level_1 = Conv(self.dim[1], self.inter_dim, 1, 1) if self.dim[1] != self.inter_dim else nn.Identity()
        self.compress_level_2 = Conv(self.dim[2], self.inter_dim, 1, 1) if self.dim[2] != self.inter_dim else nn.Identity()

    def forward(self, x):
        x_level_0, x_level_1, x_level_2 = x[0], x[1], x[2]

        if self.level == 0:
            level_0_resized = self.compress_level_0(x_level_0)
            level_1_resized = F.interpolate(self.compress_level_1(x_level_1), scale_factor=2, mode='nearest')
            level_2_resized = F.interpolate(self.compress_level_2(x_level_2), scale_factor=4, mode='nearest')
        elif self.level == 1:
            level_0_resized = F.max_pool2d(self.compress_level_0(x_level_0), 3, stride=2, padding=1)
            level_1_resized = self.compress_level_1(x_level_1)
            level_2_resized = F.interpolate(self.compress_level_2(x_level_2), scale_factor=2, mode='nearest')
        elif self.level == 2:
            level_0_resized = F.max_pool2d(self.compress_level_0(x_level_0), 3, stride=4, padding=1)
            level_1_resized = F.max_pool2d(self.compress_level_1(x_level_1), 3, stride=2, padding=1)
            level_2_resized = self.compress_level_2(x_level_2)

        weight_level_0 = self.weight_level_0(level_0_resized)
        weight_level_1 = self.weight_level_1(level_1_resized)
        weight_level_2 = self.weight_level_2(level_2_resized)
        weights = torch.cat([weight_level_0, weight_level_1, weight_level_2], dim=1)
        weights = F.softmax(weights, dim=1)

        fused_out = (level_0_resized * weights[:, 0:1, :, :] +
                     level_1_resized * weights[:, 1:2, :, :] +
                     level_2_resized * weights[:, 2:3, :, :])

        return fused_out

def autopad(k, p=None, d=1):
    if d > 1:
        k = d * (k - 1) + 1 if isinstance(k, int) else [d * (x - 1) + 1 for x in k]
    if p is None:
        p = k // 2 if isinstance(k, int) else [x // 2 for x in k]
    return p

class DWConv(nn.Module):
    def __init__(self, c1, c2, k=1, s=1, d=1, act=True):
        super().__init__()

        self.dconv = nn.Conv2d(c1, c1, k, s, padding=autopad(k, d=d), dilation=d, groups=c1, bias=False)
        self.pconv = nn.Conv2d(c1, c2, 1, 1, bias=False)
        self.bn = nn.BatchNorm2d(c2)
        self.act = nn.SiLU() if act else nn.Identity()

    def forward(self, x):
        return self.act(self.bn(self.pconv(self.dconv(x))))

class ResASPP_Optimized(nn.Module):
    def __init__(self, c1, c2, rates=(1,2,3)):
        super().__init__()
        self.shortcut = (c1 == c2)
        if not self.shortcut:
            self.cv_res = nn.Conv2d(c1, c2, 1, 1, bias=False)
            self.bn_res = nn.BatchNorm2d(c2)

        c_ = c2 // 4

        self.branch1 = Conv(c1, c_, 1, 1)
        self.branch2 = DWConv(c1, c_, 3, 1, d=rates[0])
        self.branch3 = DWConv(c1, c_, 3, 1, d=rates[1])
        self.branch4 = DWConv(c1, c_, 3, 1, d=rates[2])

        self.pool = nn.AdaptiveAvgPool2d(1)
        self.branch5 = Conv(c1, c_, 1, 1)

        self.conv_out = Conv(c_ * 5, c2, 1, 1)
        self.eca = nn.Conv2d(1, 1, kernel_size=(3, 1), padding=(1, 0), bias=False)

    def forward(self, x):
        y1 = self.branch1(x)
        y2 = self.branch2(x)
        y3 = self.branch3(x)
        y4 = self.branch4(x)

        y5 = self.pool(x)
        y5 = self.branch5(y5)
        y5 = F.interpolate(y5, size=x.shape[2:], mode='bilinear', align_corners=False)

        out = torch.cat([y1, y2, y3, y4, y5], dim=1)
        out = self.conv_out(out)

        y_attn = self.pool(out)  # [B, C, 1, 1]
        B, C, _, _ = y_attn.shape

        y_attn = y_attn.view(B, 1, C, 1)
        y_attn = self.eca(y_attn)

        y_attn = y_attn.view(B, C, 1, 1)
        out = out * torch.sigmoid(y_attn)

        if self.shortcut:
            return x + out
        else:
            return self.bn_res(self.cv_res(x)) + out

from pytorch_wavelets import DWTForward, DWTInverse


class HSG_WAVE(nn.Module):
    # 【改动1】：增加 wave_name 参数，默认保持 haar
    def __init__(self, c1, c2, alpha=0.75, wave_name='haar'):  # # 'sym4'  'coif1'  'db2'  'db6'  'sym2'  'haar'
        super().__init__()

        self.c_r = max(0, int(c1 * alpha))
        self.c_p = c1 - self.c_r

        if self.c_p < 3:
            self.c_p = c1
            self.c_r = 0

        self.c_inner = max(1, self.c_p // 3)
        self.c_p_actual = self.c_inner * 3

        self.conv_in = nn.Conv2d(self.c_p, self.c_p_actual, 1, bias=False)
        self.bn_in = nn.BatchNorm2d(self.c_p_actual)
        self.act_in = nn.SiLU(inplace=True)

        self.wave_conv = nn.Conv2d(
            self.c_inner * 4,
            self.c_inner * 4,
            kernel_size=5,
            padding=2,
            groups=self.c_inner * 4,
            bias=False
        )
        self.wave_bn = nn.BatchNorm2d(self.c_inner * 4)

        # 【改动2】：初始化通用小波变换模块
        self.wave_name = wave_name
        # mode='symmetric' 可以完美处理 db4/sym4 等长滤波器的边界填充问题
        self.dwt = DWTForward(J=1, mode='symmetric', wave=wave_name)
        self.iwt = DWTInverse(mode='symmetric', wave=wave_name)

        # 4. 融合与输出
        self.out_conv = nn.Conv2d(self.c_r + self.c_inner, c2, 1, bias=False)
        self.out_bn = nn.BatchNorm2d(c2)
        self.out_act = nn.SiLU(inplace=True)

    def forward(self, x):
        x_r, x_p = torch.split(x, [self.c_r, self.c_p], dim=1)

        x_p_all = self.act_in(self.bn_in(self.conv_in(x_p)))
        x_g, x_r_inner, x_c = torch.split(x_p_all, [self.c_inner, self.c_inner, self.c_inner], dim=1)

        # =================================================================
        # 【改动3】：使用通用库替代手工切片进行小波分解
        # Yl 是低频 LL，形状: [B, c_inner, H/2, W/2]
        # Yh 是一个列表，Yh[0] 包含高频 (LH, HL, HH)，形状: [B, c_inner, 3, H/2, W/2]
        Yl, Yh = self.dwt(x_c)

        B, C, H_half, W_half = Yl.shape
        # 将高频的维度展平，以便和 LL 拼接送入 DWConv
        # 形状变为 [B, c_inner * 3, H/2, W/2]
        Yh_reshaped = Yh[0].view(B, C * 3, H_half, W_half)

        # 拼接 LL 和 三个高频分量送入深度可分离卷积
        wave_in = torch.cat([Yl, Yh_reshaped], dim=1)
        wave_out = self.wave_bn(self.wave_conv(wave_in))

        # 卷积完成后，重新拆分出 低频 和 高频
        Yl_o, Yh_o_reshaped = torch.split(wave_out, [self.c_inner, self.c_inner * 3], dim=1)

        # 将高频部分恢复为 IWT 需要的五维张量形状 [B, c_inner, 3, H/2, W/2]
        Yh_o = Yh_o_reshaped.view(B, self.c_inner, 3, H_half, W_half)

        # 执行通用逆小波变换 (IWT)
        x_wave = self.iwt((Yl_o, [Yh_o]))

        # 【护城河设计】：防止 db4/sym4 等长滤波器引起的边缘像素多出 1~2 个
        # 强制将重构后的特征图裁剪到与原始输入相同的分辨率
        if x_wave.shape[2:] != x_g.shape[2:]:
            x_wave = x_wave[:, :, :x_g.shape[2], :x_g.shape[3]]
        # =================================================================

        x_c_out = x_wave * torch.sigmoid(x_g)
        x_fuse = x_c_out + x_r_inner

        out = self.out_conv(torch.cat([x_r, x_fuse], dim=1))
        return self.out_act(self.out_bn(out))


