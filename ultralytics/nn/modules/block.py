class CoordAtt(nn.Module):
    """
    Coordinate Attention 坐标注意力模块
    显式建模水平和垂直方向的空间位置依赖，精准补强特征的坐标信息
    专为弥补频域解耦带来的空间位置稀释问题设计
    """
    def __init__(self, in_channels, reduction=32):
        super().__init__()
        # 水平、垂直方向的全局平均池化
        self.pool_h = nn.AdaptiveAvgPool2d((None, 1))
        self.pool_w = nn.AdaptiveAvgPool2d((1, None))

        # 中间通道数压缩，保证轻量化
        reduction = reduction if reduction > 0 else 32  # 如果外部传了0，强制修正为32
        mip = max(8, in_channels // reduction)

        # 共享特征变换
        self.conv1 = nn.Conv2d(in_channels, mip, kernel_size=1, stride=1, padding=0, bias=False)
        self.bn1 = nn.BatchNorm2d(mip)
        self.act = nn.SiLU(inplace=True)

        # 分别生成水平、垂直方向的注意力权重
        self.conv_h = nn.Conv2d(mip, in_channels, kernel_size=1, stride=1, padding=0, bias=False)
        self.conv_w = nn.Conv2d(mip, in_channels, kernel_size=1, stride=1, padding=0, bias=False)

    def forward(self, x):
        identity = x
        n, c, h, w = x.size()

        # 分别沿高度、宽度方向做全局平均池化
        x_h = self.pool_h(x)  # [B, C, H, 1]
        x_w = self.pool_w(x).permute(0, 1, 3, 2)  # [B, C, W, 1] → 转置为 [B, C, W, 1]

        # 沿空间维度拼接两个方向的特征
        y = torch.cat([x_h, x_w], dim=2)
        y = self.conv1(y)
        y = self.bn1(y)
        y = self.act(y)

        # 拆分回水平、垂直两个方向
        x_h, x_w = torch.split(y, [h, w], dim=2)
        x_w = x_w.permute(0, 1, 3, 2)  # 转置回原始维度

        # 生成两个方向的注意力权重
        a_h = torch.sigmoid(self.conv_h(x_h))
        a_w = torch.sigmoid(self.conv_w(x_w))

        # 逐元素加权，输出增强后的特征
        out = identity * a_h * a_w
        return out


class HSG_WAVE_With_Mask(nn.Module):
    """
    修正版 HSG：
    1. 显式标记 produces_freq_mask；
    2. mask_generator 最后一层零初始化，使初始 mask logits=0；
    3. 对 Haar 分解所需的偶数空间尺寸做显式检查；
    4. 插值显式指定 align_corners=False。
    """
    produces_freq_mask = True

    def __init__(
        self,
        c1,
        c2,
        alpha=0.75,
        scale_idx=0,
        ca_reduction=32,
        mask_source="wavelet",
    ):
        super().__init__()
        self.set_mask_source(mask_source)
        self.scale_idx = int(scale_idx)
        self.c_r = max(0, int(c1 * alpha))
        self.c_p = c1 - self.c_r

        if self.c_p < 3:
            self.c_p = c1
            self.c_r = 0

        self.c_inner = max(1, self.c_p // 3)
        self.c_p_actual = self.c_inner * 3

        self.conv_in = nn.Conv2d(
            self.c_p,
            self.c_p_actual,
            kernel_size=1,
            bias=False,
        )
        self.bn_in = nn.BatchNorm2d(
            self.c_p_actual
        )
        self.act_in = nn.SiLU(inplace=True)

        self.wave_conv = nn.Conv2d(
            self.c_inner * 4,
            self.c_inner * 4,
            kernel_size=5,
            padding=2,
            groups=self.c_inner * 4,
            bias=False,
            padding_mode="reflect",
        )
        self.wave_bn = nn.BatchNorm2d(
            self.c_inner * 4
        )

        self.heterogeneous_gate = nn.Sequential(
            nn.Conv2d(
                self.c_inner,
                self.c_inner,
                kernel_size=1,
                bias=False,
            ),
            nn.BatchNorm2d(self.c_inner),
            nn.SiLU(inplace=True),
            nn.Conv2d(
                self.c_inner,
                1,
                kernel_size=1,
                bias=False,
            ),
            nn.Sigmoid(),
        )

        self.mask_generator = nn.Sequential(
            nn.Conv2d(
                self.c_inner * 4,
                self.c_inner * 2,
                kernel_size=3,
                padding=1,
                bias=False,
                padding_mode="reflect",
            ),
            nn.BatchNorm2d(
                self.c_inner * 2
            ),
            nn.SiLU(inplace=True),
            nn.Conv2d(
                self.c_inner * 2,
                1,
                kernel_size=1,
                bias=False,
            ),
        )

        # 初始频率 logits=0，概率=0.5；辅助损失随后驱动其学习。
        nn.init.zeros_(
            self.mask_generator[-1].weight
        )

        self.out_conv = nn.Conv2d(
            self.c_r + self.c_inner,
            c2,
            kernel_size=1,
            bias=False,
        )
        self.out_bn = nn.BatchNorm2d(c2)
        self.coord_att = CoordAtt(
            in_channels=c2,
            reduction=ca_reduction,
        )
        self.out_act = nn.SiLU(inplace=True)

        # 只关闭附加 mask 残差，不表示整个 HSG 是恒等映射。
        self.mask_alpha = nn.Parameter(
            torch.zeros(1)
        )

    def set_mask_source(self, source):
        """Select downstream guidance without changing the wavelet detection branch."""
        if source not in {"wavelet", "spatial"}:
            raise ValueError(f"unsupported mask_source={source!r}")
        self.mask_source = source

    def configure_evidence(self, mode):
        """Add only downstream heads; the original head continues to gate HSG."""
        if mode not in {"shared", "independent"}:
            raise ValueError(f"unsupported evidence mode {mode!r}")
        if mode == "shared" and hasattr(self, "acsa_mask_generator"):
            raise ValueError("rebuild a shared model instead of reusing independent evidence parameters")
        self.evidence_mode = mode
        if mode == "independent" and not hasattr(self, "acsa_mask_generator"):
            self.acsa_mask_generator = copy.deepcopy(self.mask_generator)
            self.query_mask_generator = copy.deepcopy(self.mask_generator)

    def initialize_independent_evidence(self):
        for name in ("acsa_mask_generator", "query_mask_generator"):
            if hasattr(self, name):
                getattr(self, name).load_state_dict(self.mask_generator.state_dict(), strict=True)

    def forward(self, x, return_evidence=False):
        original_h, original_w = x.shape[-2:]

        if original_h % 2 != 0 or original_w % 2 != 0:
            raise ValueError(
                "HSG_WAVE_With_Mask 的 Haar 分解要求特征图高宽为偶数，"
                f"当前为 {(original_h, original_w)}。"
                "请确保输入 imgsz 为 32 的倍数。"
            )

        x_r, x_p = torch.split(
            x,
            [self.c_r, self.c_p],
            dim=1,
        )

        x_p_all = self.act_in(
            self.bn_in(
                self.conv_in(x_p)
            )
        )
        x_g, x_r_inner, x_c = torch.split(
            x_p_all,
            [
                self.c_inner,
                self.c_inner,
                self.c_inner,
            ],
            dim=1,
        )

        x0 = x_c[:, :, 0::2, 0::2]     # 小波分解
        x1 = x_c[:, :, 1::2, 0::2]
        x2 = x_c[:, :, 0::2, 1::2]
        x3 = x_c[:, :, 1::2, 1::2]

        ll = (x0 + x1 + x2 + x3) / 2.0
        hl = (x0 - x1 + x2 - x3) / 2.0
        lh = (x0 + x1 - x2 - x3) / 2.0
        hh = (x0 - x1 - x2 + x3) / 2.0

        wave_in = torch.cat(
            [ll, hl, lh, hh],
            dim=1,
        )
        wave_out = self.wave_bn(
            self.wave_conv(wave_in)
        )
        ll_o, hl_o, lh_o, hh_o = torch.split(
            wave_out,
            [self.c_inner] * 4,
            dim=1,
        )

        spatial_attn = self.heterogeneous_gate(
            ll_o
        )
        enhanced_high_freq = torch.cat(
            [hl_o, lh_o, hh_o],
            dim=1,
        ) * spatial_attn

        enhanced_full = torch.cat(             # 低频LL引导后的特征图
            [ll_o, enhanced_high_freq],
            dim=1,
        )
        mask_raw = self.mask_generator(        # 生成全局频率掩码
            enhanced_full
        )

        y0 = (
            ll_o + hl_o + lh_o + hh_o
        ) / 2.0
        y1 = (
            ll_o - hl_o + lh_o - hh_o
        ) / 2.0
        y2 = (
            ll_o + hl_o - lh_o - hh_o
        ) / 2.0
        y3 = (
            ll_o - hl_o - lh_o + hh_o
        ) / 2.0

        b, c, h, w = y0.shape
        x_wave = torch.empty(
            b,
            c,
            h * 2,
            w * 2,
            device=x.device,
            dtype=x.dtype,
        )
        x_wave[:, :, 0::2, 0::2] = y0  # 逆小波变换
        x_wave[:, :, 1::2, 0::2] = y1
        x_wave[:, :, 0::2, 1::2] = y2
        x_wave[:, :, 1::2, 1::2] = y3

        freq_mask = F.interpolate(
            mask_raw,
            size=(original_h, original_w),
            mode="bilinear",
            align_corners=False,
        )

        x_fuse = (
            x_wave * torch.sigmoid(x_g)
            + x_r_inner
        )

        x_out = self.out_bn(
            self.out_conv(
                torch.cat(
                    [x_r, x_fuse],
                    dim=1,
                )
            )
        )
        out = self.out_act(
            self.coord_att(x_out)
        )

        out_enhanced = (
            out + self.mask_alpha * (out * torch.sigmoid(freq_mask))
        )
        # The learned detection residual above MUST still use the wavelet mask.
        # Old pickled checkpoints have no mask_source attribute and retain their exact path.
        if getattr(self, "mask_source", "wavelet") == "spatial":
            spatial_input = F.pixel_unshuffle(x_c, 2)
            if spatial_input.shape != enhanced_full.shape:
                raise RuntimeError("spatial guidance input must match the wavelet mask input shape")
            freq_mask = F.interpolate(
                self.mask_generator(spatial_input), size=(original_h, original_w),
                mode="bilinear", align_corners=False,
            )
        if return_evidence:
            if getattr(self, "evidence_mode", "shared") == "independent":
                if getattr(self, "mask_source", "wavelet") != "wavelet":
                    raise ValueError("independent evidence requires shared wavelet features")
                evidence = {
                    name: F.interpolate(generator(enhanced_full), size=(original_h, original_w),
                                        mode="bilinear", align_corners=False)
                    for name, generator in (("acsa", self.acsa_mask_generator),
                                            ("query", self.query_mask_generator))
                }
            else:
                evidence = {"acsa": freq_mask, "query": freq_mask}
            return out_enhanced, freq_mask, evidence
        return out_enhanced, freq_mask


from torchvision.ops import DeformConv2d
import math
import torch
import torch.nn as nn
import torch.nn.functional as F


class ECA(nn.Module):
    """轻量级高效通道注意力机制 (Efficient Channel Attention)"""

    def __init__(self, channel, b=1, gamma=2):
        super().__init__()
        # 自适应计算 1D 卷积的核大小
        kernel_size = int(abs((math.log(channel, 2) + b) / gamma))
        kernel_size = kernel_size if kernel_size % 2 else kernel_size + 1

        self.avg_pool = nn.AdaptiveAvgPool2d(1)
        self.conv = nn.Conv1d(1, 1, kernel_size=kernel_size, padding=(kernel_size - 1) // 2, bias=False)
        self.sigmoid = nn.Sigmoid()

    def forward(self, x):
        y = self.avg_pool(x)
        # 维度转换以适配 Conv1d: (B, C, 1, 1) -> (B, 1, C)
        y = self.conv(y.squeeze(-1).transpose(-1, -2)).transpose(-1, -2).unsqueeze(-1)
        return x * self.sigmoid(y)


# HSG 负责发现频率显著区域；
# ACSA_FG 负责让 DCNv2 朝这些区域更合理地采样。


class ACSA_FG(nn.Module):
    """
    修正版 ACSA-FG：
    1. 显式标记 consumes_freq_masks，避免外层用 hasattr(scale_idx) 误判；
    2. offset/mask 预测层零初始化，初始 offset=0、DCN mask=0.5；
    3. 频率掩码在 logit 空间调制 DCN mask，保证最终 mask 始终位于 0~1；
    4. 前置特征调制以 0.5 为中性点，初始不会整体放大特征。
    """
    consumes_freq_masks = True

    def __init__(
        self,
        c1,
        c2,
        split_ratio="0.5",
        use_freq_guidance=True,
        scale_idx=0,
        freq_guidance_beta=1.0,
    ):
        super().__init__()
        self.c1 = int(c1)
        self.c2 = int(c2)
        self.scale_idx = int(scale_idx)
        self.freq_guidance_beta = float(freq_guidance_beta)

        self.split_ratio = float(split_ratio)
        self.use_freq_guidance = (
            use_freq_guidance
            if isinstance(use_freq_guidance, bool)
            else str(use_freq_guidance).lower() == "true"
        )
        if not 0.0 < self.split_ratio < 1.0:
            raise ValueError("split_ratio must be between 0 and 1")

        self.split_channels = int(self.c2 * self.split_ratio)
        self.dcn_channels = self.c2 - self.split_channels
        if self.split_channels <= 0 or self.dcn_channels <= 0:
            raise ValueError(
                f"非法通道划分：c2={self.c2}, split_ratio={self.split_ratio}"
            )

        self.proj_in = nn.Sequential(
            nn.Conv2d(self.c1, self.c2, kernel_size=1, bias=False),
            nn.BatchNorm2d(self.c2),
            nn.SiLU(inplace=True),
        )

        self.conv_sem = nn.Sequential(
            nn.Conv2d(
                self.split_channels,
                self.split_channels,
                kernel_size=3,
                padding=1,
                bias=False,
            ),
            nn.BatchNorm2d(self.split_channels),
            nn.SiLU(inplace=True),
            ECA(self.split_channels),
        )

        self.offset_net = nn.Sequential(
            nn.Conv2d(
                self.dcn_channels,
                self.dcn_channels,
                kernel_size=3,
                padding=1,
                groups=self.dcn_channels,
                bias=False,
            ),
            nn.BatchNorm2d(self.dcn_channels),
            nn.SiLU(inplace=True),
            nn.Conv2d(self.dcn_channels, 27, kernel_size=1, bias=True),
        )

        # 稳定初始化：18 个 offset 初始为 0，9 个 mask logits 初始为 0。
        nn.init.zeros_(self.offset_net[-1].weight)
        nn.init.zeros_(self.offset_net[-1].bias)

        self.dcn = DeformConv2d(
            self.dcn_channels,
            self.dcn_channels,
            kernel_size=3,
            padding=1,
            bias=False,
        )
        self.bn_dcn = nn.BatchNorm2d(self.dcn_channels)

        self.proj_out = nn.Sequential(
            nn.Conv2d(self.c2, self.c2, kernel_size=1, bias=False),
            nn.BatchNorm2d(self.c2),
        )

        self.proj_res = (
            nn.Conv2d(self.c1, self.c2, kernel_size=1, bias=False)
            if self.c1 != self.c2
            else nn.Identity()
        )
        self.gamma = nn.Parameter(torch.ones(1, self.c2, 1, 1) * 1e-4)

    @staticmethod
    def _align_mask(mask_logits: torch.Tensor, target_hw: tuple[int, int]) -> torch.Tensor:    # 负责把来自 HSG 的 freq_mask 对齐到当前 ACSA 特征尺寸
        target_h, target_w = target_hw
        mask_h, mask_w = mask_logits.shape[-2:]

        if (mask_h, mask_w) == (target_h, target_w):
            return mask_logits

        if mask_h >= target_h and mask_w >= target_w:
            return F.adaptive_avg_pool2d(mask_logits, output_size=(target_h, target_w))

        return F.interpolate(
            mask_logits,
            size=(target_h, target_w),
            mode="bilinear",
            align_corners=False,
        )

    def configure_freq_guidance(self, beta: float, enabled: bool | None = None) -> None:
        """Configure non-parametric frequency guidance without changing serialized module state."""
        beta = float(beta)
        if not math.isfinite(beta) or beta < 0.0:
            raise ValueError(f"ACSA frequency-guidance beta must be finite and nonnegative, got {beta}")
        self.freq_guidance_beta = beta
        if enabled is not None:
            self.use_freq_guidance = bool(enabled)

    def forward(self, x, freq_masks: dict | None = None):
        res = self.proj_res(x)
        x = self.proj_in(x)

        x_sem, x_geo = torch.split(
            x,
            [self.split_channels, self.dcn_channels],
            dim=1,
        )

        y_sem = self.conv_sem(x_sem)

        aligned_mask_logits = None
        guided_x_geo = x_geo

        if (                                        # 如果引导图存在
            self.use_freq_guidance
            and freq_masks is not None
            and self.scale_idx in freq_masks
        ):
            aligned_mask_logits = self._align_mask(        # 如果引导图存在，将引导图与原始特征图对齐，将频率引导图赋予aligned_mask_logits
                freq_masks[self.scale_idx],
                target_hw=x_geo.shape[-2:],
            ).to(dtype=x_geo.dtype)

            aligned_mask_prob = torch.sigmoid(aligned_mask_logits)

            # 0.5 为中性点：mask logits=0 时 guided_x_geo == x_geo ，mask_prob > 0.5 → 正向增强 ，mask_prob < 0.5 → 抑制
            centered_guidance = aligned_mask_prob - 0.5
            guided_x_geo = x_geo * (                                # 更新几何分支（特征图）
                1.0 + self.freq_guidance_beta * centered_guidance
            )

        dcn_params = self.offset_net(guided_x_geo)    # 频率引导会影响dcn参数的预测
        offset, dcn_mask_logits = torch.split(dcn_params, [18, 9], dim=1)   # 频率引导主要预测offset（每个采样点的位置偏移）和dcn_mask_logits（每个采样点的调制权重 logits）

        if aligned_mask_logits is not None:
            # 在 logit 空间耦合，最终 sigmoid 后仍严格位于 0~1。
            dcn_mask_logits = (
                dcn_mask_logits
                + self.freq_guidance_beta * aligned_mask_logits
            )

        dcn_mask = torch.sigmoid(dcn_mask_logits)

        y_geo = self.dcn(x_geo, offset, mask=dcn_mask)
        y_geo = F.silu(self.bn_dcn(y_geo), inplace=True)

        out = torch.cat([y_sem, y_geo], dim=1)
        out = self.proj_out(out)

        return F.silu(res + self.gamma * out, inplace=True)
