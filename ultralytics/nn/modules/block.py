class ESSamp(nn.Module):
    def __init__(self, c1, c2, k=3, d=2):
        super().__init__()
        self.unshuffle = nn.PixelUnshuffle(2)
        c_unshuffled = c1 * 4
        c_dw = c_unshuffled * d

        self.edw = nn.Conv2d(c_unshuffled, c_dw, kernel_size=k, stride=1, padding=autopad(k), groups=c_unshuffled,
                             bias=False)
        self.bn1 = nn.BatchNorm2d(c_dw)
        self.act1 = nn.GELU()

        self.pw = nn.Conv2d(c_dw, c2, kernel_size=1, stride=1, padding=0, bias=False)
        self.bn2 = nn.BatchNorm2d(c2)
        self.act2 = nn.GELU()

    def forward(self, x):
        x = self.unshuffle(x)
        x = self.act1(self.bn1(self.edw(x)))
        x = self.act2(self.bn2(self.pw(x)))
        return x

