def run_evaluation(
    args: argparse.Namespace,
    patch_cache: Path,
    merged_cache: Path,
    expected_inference_metadata: dict[str, Any],
) -> None:
    out_dir = Path(args.out).expanduser().resolve()
    ann_dir = Path(args.ori_ann_dir).expanduser().resolve()

    # STAGE='eval' can run without inference, so validate here as well.
    validate_official_poly2obb_converter()

    gt_map = load_original_gt(
        ann_dir,
        min_obb_side=args.min_obb_side,
    )
    original_ids = sorted(gt_map.keys())
    annotations = [gt_map[image_id] for image_id in original_ids]

    expected_merged_metadata = build_merged_metadata(
        expected_inference_metadata,
        original_ids,
        args.merge_iou,
    )

    if args.reuse_merged_cache and merged_cache.exists():
        merged_results = load_merged_cache_validated(
            merged_cache,
            expected_merged_metadata,
        )
        print(f"[MERGE] reused validated cache: {merged_cache}")
    else:
        if not patch_cache.exists():
            raise FileNotFoundError(
                f"Patch prediction cache does not exist: {patch_cache}. "
                "Run STAGE='infer' or STAGE='all' first."
            )

        patch_payload = load_patch_cache_validated(
            patch_cache,
            expected_inference_metadata,
        )

        merged_results = merge_patch_predictions(
            patch_payload=patch_payload,
            original_ids=original_ids,
            merge_iou=args.merge_iou,
            merge_device=args.merge_device,
        )

        with merged_cache.open("wb") as file:
            pickle.dump(
                {
                    "metadata": expected_merged_metadata,
                    "results": merged_results,
                },
                file,
                protocol=pickle.HIGHEST_PROTOCOL,
            )
        print(f"[MERGE] cache: {merged_cache}")

    if len(merged_results) != len(original_ids):
        raise RuntimeError(
            "Merged result count does not match GT image count: "
            f"{len(merged_results)} != {len(original_ids)}"
        )

    SODAAeval = import_official_sodaa_eval(args.sodaa_eval)
    (out_dir / "work_dirs").mkdir(parents=True, exist_ok=True)

    evaluator = SODAAeval(
        annotations=annotations,
        results=merged_results,
        numCats=NUM_CLASSES,
        nproc=args.eval_workers,
    )
    evaluator.params.iouThrs = np.linspace(
        0.50,
        0.95,
        int(round((0.95 - 0.50) / 0.05)) + 1,
        endpoint=True,
    )

    with working_directory(out_dir):
        evaluator.evaluate()
        install_numpy_legacy_aliases()
        evaluator.accumulate()
        evaluator.summarize()

    class_rows = per_class_metrics(evaluator)
    save_metrics(
        out_dir=out_dir,
        eval_obj=evaluator,
        original_ids=original_ids,
        per_class_rows=class_rows,
        run_metadata=expected_merged_metadata,
    )


