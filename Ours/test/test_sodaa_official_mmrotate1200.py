def prepare_mmrotate_style_patch(
    image: np.ndarray,
    content_size: int,
    pad_divisor: int,
    padding_value: int | float = 114,
) -> tuple[np.ndarray, dict[str, Any]]:
    """Apply MMRotate-style keep-ratio resize and top-left divisor padding."""
    if not isinstance(image, np.ndarray):
        raise TypeError(f"image must be np.ndarray, got {type(image)}.")
    if image.ndim != 3 or image.shape[2] != 3:
        raise ValueError(
            "image must have shape (H, W, 3), "
            f"got {image.shape}."
        )
    original_h, original_w = image.shape[:2]
    if original_h <= 0 or original_w <= 0:
        raise ValueError(f"image has an empty spatial shape: {image.shape}.")
    if content_size <= 0:
        raise ValueError(
            f"content_size must be positive, got {content_size}."
        )
    if pad_divisor <= 0:
        raise ValueError(
            f"pad_divisor must be positive, got {pad_divisor}."
        )
    if not 0 <= padding_value <= 255:
        raise ValueError(
            f"padding_value must be in [0, 255], got {padding_value}."
        )

    scale = min(
        float(content_size) / float(original_w),
        float(content_size) / float(original_h),
    )
    resized_w = max(int(original_w * scale + 0.5), 1)
    resized_h = max(int(original_h * scale + 0.5), 1)
    resized = cv2.resize(
        image,
        (resized_w, resized_h),
        interpolation=cv2.INTER_LINEAR,
    )

    input_w = (
        (resized_w + int(pad_divisor) - 1)
        // int(pad_divisor)
        * int(pad_divisor)
    )
    input_h = (
        (resized_h + int(pad_divisor) - 1)
        // int(pad_divisor)
        * int(pad_divisor)
    )
    canvas_shape = (input_h, input_w, *image.shape[2:])
    canvas = np.full(canvas_shape, padding_value, dtype=image.dtype)
    canvas[:resized_h, :resized_w, ...] = resized

    transform = {
        "original_shape": (int(original_h), int(original_w)),
        "resized_shape": (int(resized_h), int(resized_w)),
        "input_shape": (int(input_h), int(input_w)),
        "scale_x": float(resized_w) / float(original_w),
        "scale_y": float(resized_h) / float(original_h),
        "pad_left": 0,
        "pad_top": 0,
        "pad_right": int(input_w - resized_w),
        "pad_bottom": int(input_h - resized_h),
    }
    return canvas, transform


def restore_polygons_to_patch(
    polygons: np.ndarray,
    transform: dict[str, Any],
) -> np.ndarray:
    """Invert padding and resizing for padded-canvas polygon predictions."""
    restored = np.asarray(polygons, dtype=np.float32).copy()
    if restored.ndim < 2 or restored.shape[-1] != 2:
        raise ValueError(
            "polygons must end with an (x, y) coordinate dimension, "
            f"got {restored.shape}."
        )
    if not np.isfinite(restored).all():
        raise ValueError("polygons contain NaN or infinite coordinates.")

    scale_x = float(transform["scale_x"])
    scale_y = float(transform["scale_y"])
    pad_left = float(transform["pad_left"])
    pad_top = float(transform["pad_top"])
    if (
        not np.isfinite([scale_x, scale_y, pad_left, pad_top]).all()
        or scale_x <= 0.0
        or scale_y <= 0.0
    ):
        raise ValueError(f"invalid preprocessing transform: {transform}.")

    restored[..., 0] = (restored[..., 0] - pad_left) / scale_x
    restored[..., 1] = (restored[..., 1] - pad_top) / scale_y
    return restored


def file_sha256(path: Path, chunk_size: int = 8 * 1024 * 1024) -> str:
    """Return a stable SHA-256 fingerprint for cache validation."""
    digest = hashlib.sha256()
    with path.open("rb") as file:
        while True:
            block = file.read(chunk_size)
            if not block:
                break
            digest.update(block)
    return digest.hexdigest()


def file_identity(path: Path, include_sha256: bool = True) -> dict[str, Any]:
    path = path.expanduser().resolve()
    stat = path.stat()
    identity: dict[str, Any] = {
        "path": str(path),
        "size": int(stat.st_size),
        "mtime_ns": int(stat.st_mtime_ns),
    }
    if include_sha256:
        identity["sha256"] = file_sha256(path)
    return identity


def poly2obb_np_official(
    poly: np.ndarray,
    min_side: float = MIN_OBB_SIDE,
) -> np.ndarray | None:
    """Convert an 8-value polygon with official MMRotate ``poly2obb_np``."""
    try:
        polygon = np.asarray(poly, dtype=np.float32).reshape(-1)
    except (TypeError, ValueError):
        return None

    if polygon.size != 8 or not np.isfinite(polygon).all():
        return None

    converter = import_official_poly2obb_np()
    try:
        rbbox = converter(polygon, OFFICIAL_ANGLE_VERSION)
    except Exception:
        return None

    if rbbox is None:
        return None

    try:
        rbbox = np.asarray(rbbox, dtype=np.float32).reshape(5)
    except (TypeError, ValueError):
        return None

    if not np.isfinite(rbbox).all():
        return None
    if float(rbbox[2]) <= min_side or float(rbbox[3]) <= min_side:
        return None

    return rbbox


