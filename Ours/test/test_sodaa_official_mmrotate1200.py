def resolve_original_annotation_dir() -> Path:
    """Resolve the original-image GT directory, preferring AnnsWoIgnore."""
    candidates = [ORIGINAL_ANN_DIR, *ORIGINAL_ANN_FALLBACKS]
    seen: set[Path] = set()
    resolved: list[Path] = []
    for value in candidates:
        path = Path(value).expanduser().resolve()
        if path not in seen:
            seen.add(path)
            resolved.append(path)

    for path in resolved:
        if path.is_dir():
            if path.name != "AnnsWoIgnore":
                print(
                    "[WARN] Official AnnsWoIgnore directory was not found; "
                    f"using {path} and filtering category_id==9 in memory."
                )
            else:
                print(f"[GT] using official ignore-filtered annotations: {path}")
            return path

    tried = "\n".join(f"  - {path}" for path in resolved)
    raise FileNotFoundError(
        "Could not locate SODA-A original-image test annotations. Tried:\n"
        f"{tried}"
    )


