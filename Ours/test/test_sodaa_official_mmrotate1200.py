"""
SODA-A original-image-level evaluation pipeline for a custom Ultralytics
RT-DETR-OBB model.

Pipeline
--------
1. infer:
   - Run OBB inference on official SODA-A test patches with independent
     multi-GPU workers (one model replica per GPU).
   - Reproduce the official SODA-A/MMRotate test geometry: resize each
     official 800x800 patch to 1200x1200, then top-left pad to the next
     multiple of 32 (1216x1216).
   - Read patch offsets from patch_manifest.csv.
   - Invert preprocessing before mapping predictions to original images.
   - Save patch_predictions.pkl with strict inference metadata.

2. eval:
   - Merge overlapping patch predictions with class-wise rotated NMS.
   - Load original-image SODA-A test annotations with ignore regions removed.
   - Run the official SODAAeval implementation.
   - Save AP/AP50/AP75/scale metrics and per-class AP.

3. all:
   - Run inference, merge, and official evaluation.

Important safeguards
--------------------
- Forces the custom model task to "obb".
- Verifies that prediction results really contain result.obb.
- Uses FP32 inference by default and does not pass the deprecated half argument.
- Uses CUDA-safe multiprocessing with the ``spawn`` start method.
- Splits patches into contiguous non-overlapping shards, checks for no
  missing/duplicate patches, and merges shards in manifest order.
- Binds preprocessing geometry to cache metadata to reject stale caches.
- Validates cache metadata to prevent evaluating stale predictions.
- Uses the selected GPU for rotated NMS instead of hard-coding cuda:0.
- Uses the official bundled MMRotate ``poly2obb_np(..., 'le90')`` conversion by loading ``core/bbox/transforms.py`` directly, avoiding legacy MMRotate package initialization.
- Reports detailed reasons for filtered GT annotations.
- Does not discard valid tiny boxes merely because a side is below 2 pixels.
- Keeps the custom Ultralytics model's native normalization; only the official
  SODA-A test *geometry* is reproduced.
"""

