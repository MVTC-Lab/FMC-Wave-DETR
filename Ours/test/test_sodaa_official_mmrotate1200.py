def load_merged_cache_validated(
    merged_cache: Path,
    expected_metadata: dict[str, Any],
) -> list[list[np.ndarray]]:
    with merged_cache.open("rb") as file:
        payload = pickle.load(file)

    if "results" not in payload:
        raise KeyError(f"Merged cache has no 'results': {merged_cache}")
    if "metadata" not in payload:
        raise RuntimeError(
            "Merged cache has no strict metadata and is treated as stale. "
            f"Regenerate it: {merged_cache}"
        )

    compare_metadata(
        payload["metadata"],
        expected_metadata,
        prefix="Merged cache",
    )
    return payload["results"]


def per_class_metrics(eval_obj) -> list[dict[str, Any]]:
    precision = eval_obj.eval["precision"]
    rows: list[dict[str, Any]] = []

    ap75_matches = np.where(
        np.isclose(eval_obj.params.iouThrs, 0.75)
    )[0]
    if len(ap75_matches) != 1:
        raise RuntimeError("Could not identify the AP75 IoU index.")
    ap75_index = int(ap75_matches[0])

    for class_id, class_name in enumerate(CLASS_NAMES):
        all_ap = precision[:, :, class_id, 0, -1]
        all_ap = all_ap[all_ap > -1]
        ap = float(np.mean(all_ap)) if all_ap.size else float("nan")

        ap50_values = precision[0, :, class_id, 0, -1]
        ap50_values = ap50_values[ap50_values > -1]
        ap50 = (
            float(np.mean(ap50_values))
            if ap50_values.size
            else float("nan")
        )

        ap75_values = precision[ap75_index, :, class_id, 0, -1]
        ap75_values = ap75_values[ap75_values > -1]
        ap75 = (
            float(np.mean(ap75_values))
            if ap75_values.size
            else float("nan")
        )

        rows.append(
            {
                "class_id": class_id,
                "class_name": class_name,
                "AP": ap,
                "AP50": ap50,
                "AP75": ap75,
            }
        )

    return rows


