def load_original_gt(
    ann_dir: Path,
    min_obb_side: float,
) -> dict[str, dict[str, np.ndarray]]:
    if not ann_dir.is_dir():
        raise FileNotFoundError(
            f"Original test annotation directory does not exist: {ann_dir}"
        )

    annotations_by_id: dict[str, dict[str, np.ndarray]] = {}
    reasons: Counter[str] = Counter()
    examples: dict[str, tuple[str, Any]] = {}

    def record(reason: str, json_path: Path, ann: Any) -> None:
        reasons[reason] += 1
        examples.setdefault(reason, (str(json_path), ann))

    for json_path in sorted(ann_dir.rglob("*.json")):
        data = json.loads(json_path.read_text(encoding="utf-8-sig"))
        anns = data.get("annotations", [])
        if not isinstance(anns, list):
            raise ValueError(f"'annotations' is not a list: {json_path}")

        bboxes: list[np.ndarray] = []
        labels: list[int] = []

        for ann in anns:
            category_value = ann.get(
                "category_id",
                ann.get("cat_id"),
            )
            try:
                category_id = int(category_value)
            except (TypeError, ValueError):
                record("invalid_category", json_path, ann)
                continue

            if category_id == 9:
                record("ignore_category_9", json_path, ann)
                continue

            if not 0 <= category_id < NUM_CLASSES:
                record("category_out_of_range", json_path, ann)
                continue

            try:
                poly = np.asarray(
                    ann.get("poly", []),
                    dtype=np.float32,
                ).reshape(-1)
            except (TypeError, ValueError):
                record("poly_conversion_failed", json_path, ann)
                continue

            if poly.size != 8:
                record(f"poly_length_{poly.size}", json_path, ann)
                continue
            if not np.isfinite(poly).all():
                record("poly_nan_or_inf", json_path, ann)
                continue

            rbbox = poly2obb_np_official(
                poly,
                min_side=min_obb_side,
            )
            if rbbox is None:
                record("invalid_or_degenerate_official_poly2obb", json_path, ann)
                continue

            bboxes.append(rbbox)
            labels.append(category_id)

        annotations_by_id[json_path.stem] = {
            "bboxes": (
                np.asarray(bboxes, dtype=np.float32).reshape(-1, 5)
                if bboxes
                else np.zeros((0, 5), dtype=np.float32)
            ),
            "labels": np.asarray(labels, dtype=np.int64),
        }

    if not annotations_by_id:
        raise RuntimeError(
            f"No original test annotations parsed from: {ann_dir}"
        )

    print(f"[GT] original images: {len(annotations_by_id)}")
    print("[GT] annotation filtering summary:")
    for reason, count in reasons.most_common():
        print(f"  {reason:<28}: {count}")

    invalid_count = sum(
        count
        for reason, count in reasons.items()
        if reason != "ignore_category_9"
    )
    print(
        f"[GT] ignore annotations skipped: "
        f"{reasons.get('ignore_category_9', 0)}"
    )
    print(f"[GT] invalid annotations skipped: {invalid_count}")

    if invalid_count:
        print("[GT] first invalid example for each reason:")
        for reason, (file_path, ann) in examples.items():
            if reason == "ignore_category_9":
                continue
            print(f"  - {reason}: {file_path}")
            print(f"    annotation={ann}")

    return annotations_by_id


def torch_device_from_string(device_value: str):
    import torch

    text = str(device_value).strip().lower()
    if text == "cpu" or not torch.cuda.is_available():
        return torch.device("cpu")

    # Accept "6", "cuda:6", or "6,7"; use the first GPU for merge NMS.
    first = text.split(",")[0].strip()
    if first.startswith("cuda:"):
        index = first.split(":", maxsplit=1)[1]
    else:
        index = first

    if not index.isdigit():
        raise ValueError(
            f"Unsupported MERGE_DEVICE={device_value!r}. "
            "Use 'cpu', '6', or 'cuda:6'."
        )
    return torch.device(f"cuda:{index}")


def merge_patch_predictions(
    patch_payload: dict[str, Any],
    original_ids: list[str],
    merge_iou: float,
    merge_device: str,
) -> list[list[np.ndarray]]:
    try:
        import torch
        from mmcv.ops import nms_rotated
    except Exception as exc:
        raise RuntimeError(
            "Official merging requires working MMCV compiled ops. "
            "Test with: python -c "
            "\"from mmcv.ops import nms_rotated, box_iou_rotated; print('OK')\""
        ) from exc

    device = torch_device_from_string(merge_device)
    print(f"[MERGE] rotated NMS device: {device}")

    patch_predictions = patch_payload["predictions"]
    merged_results: list[list[np.ndarray]] = []

    total_before = 0
    total_after = 0

    for original_id in tqdm(original_ids, desc="Official rotated merge"):
        per_class: list[np.ndarray] = []
        source_map = patch_predictions.get(original_id, {})

        for class_id in range(NUM_CLASSES):
            dets = source_map.get(class_id)
            if dets is None or len(dets) == 0:
                per_class.append(np.zeros((0, 6), dtype=np.float32))
                continue

            dets = np.asarray(dets, dtype=np.float32).reshape(-1, 6)
            finite_rows = np.isfinite(dets).all(axis=1)
            dets = dets[finite_rows]
            total_before += len(dets)

            if len(dets) == 0:
                per_class.append(np.zeros((0, 6), dtype=np.float32))
                continue

            boxes = torch.from_numpy(dets[:, :5]).to(device).contiguous()
            scores = torch.from_numpy(dets[:, 5]).to(device).contiguous()

            nms_output, _ = nms_rotated(boxes, scores, merge_iou)
            merged = nms_output.detach().cpu().numpy().astype(np.float32)

            per_class.append(merged)
            total_after += len(merged)

        merged_results.append(per_class)

    print(f"[MERGE] detections before NMS: {total_before}")
    print(f"[MERGE] detections after NMS:  {total_after}")
    return merged_results


