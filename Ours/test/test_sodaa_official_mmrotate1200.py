def compare_metadata(
    cached: dict[str, Any],
    expected: dict[str, Any],
    prefix: str,
) -> None:
    if cached != expected:
        cached_text = json.dumps(cached, ensure_ascii=False, indent=2)
        expected_text = json.dumps(expected, ensure_ascii=False, indent=2)
        raise RuntimeError(
            f"{prefix} metadata does not match the current configuration.\n"
            "Do not reuse this cache.\n"
            f"Cached metadata:\n{cached_text}\n"
            f"Current metadata:\n{expected_text}"
        )


def load_patch_cache_validated(
    patch_cache: Path,
    expected_metadata: dict[str, Any],
) -> dict[str, Any]:
    with patch_cache.open("rb") as file:
        payload = pickle.load(file)

    if "predictions" not in payload:
        raise KeyError(f"Patch cache has no 'predictions': {patch_cache}")
    if "metadata" not in payload:
        raise RuntimeError(
            "Patch cache has no strict metadata and is treated as stale. "
            f"Regenerate it: {patch_cache}"
        )

    compare_metadata(
        payload["metadata"],
        expected_metadata,
        prefix="Patch cache",
    )
    return payload



def split_contiguous(
    items: list[Any],
    parts: int,
) -> list[list[Any]]:
    """
    Split a list into contiguous, near-equal shards.

    Contiguous partitioning is intentional: when worker shards are merged in
    rank order, prediction row ordering remains consistent with the original
    manifest traversal as closely as possible.
    """
    if parts <= 0:
        raise ValueError(f"parts must be positive, got {parts}.")

    n = len(items)
    base, remainder = divmod(n, parts)

    shards: list[list[Any]] = []
    start = 0

    for rank in range(parts):
        size = base + (1 if rank < remainder else 0)
        stop = start + size
        shards.append(items[start:stop])
        start = stop

    if start != n:
        raise RuntimeError(
            f"Internal shard split error: consumed {start}, expected {n}."
        )

    return shards


def serialize_worker_collector(
    collector: dict[str, dict[int, list[np.ndarray]]],
) -> dict[str, dict[int, np.ndarray]]:
    serializable: dict[str, dict[int, np.ndarray]] = {}

    for original_id, class_map in collector.items():
        serializable[original_id] = {}
        for class_id, arrays in class_map.items():
            serializable[original_id][int(class_id)] = (
                np.concatenate(arrays, axis=0).astype(np.float32, copy=False)
                if arrays
                else np.zeros((0, 6), dtype=np.float32)
            )

    return serializable


def inference_worker(
    worker_rank: int,
    device: str,
    assigned_records: list[tuple[str, str, dict[str, Any]]],
    args_dict: dict[str, Any],
    shard_path_str: str,
) -> dict[str, Any]:
    """
    Run one independent inference shard on one GPU.

    The worker writes its predictions to a private pickle file.  Workers never
    write the shared final patch_predictions.pkl file.
    """
    args = argparse.Namespace(**args_dict)
    shard_path = Path(shard_path_str).expanduser().resolve()
    shard_path.parent.mkdir(parents=True, exist_ok=True)

    # Avoid thread oversubscription when four Python processes decode/resize
    # images concurrently.
    try:
        cv2.setNumThreads(0)
    except Exception:
        pass

    print(
        f"[GPU-WORKER {worker_rank}] device={device}, "
        f"patches={len(assigned_records)}, "
        f"batch={args.batch_per_gpu}",
        flush=True,
    )

    model_path = Path(args.model).expanduser().resolve()
    model = load_custom_obb_model(model_path)

    collector: dict[str, dict[int, list[np.ndarray]]] = defaultdict(
        lambda: defaultdict(list)
    )

    processed_patch_ids: list[str] = []
    detections = 0
    skipped_invalid_prediction = 0
    saturated_patches = 0
    first_result_checked = False
    first_geometry_printed = False
    start_time = time.time()

    progress = tqdm(
        total=len(assigned_records),
        desc=f"GPU {device}",
        position=worker_rank,
        leave=True,
        dynamic_ncols=True,
    )

    try:
        for record_batch in batched(
            assigned_records,
            args.batch_per_gpu,
        ):
            batch_images: list[np.ndarray] = []
            batch_transforms: list[dict[str, Any]] = []
            batch_patch_ids: list[str] = []
            batch_paths: list[Path] = []
            batch_metas: list[dict[str, Any]] = []

            for patch_id, patch_path_str, meta in record_batch:
                patch_path = Path(patch_path_str)
                image = cv2.imread(str(patch_path), cv2.IMREAD_COLOR)

                if image is None:
                    raise RuntimeError(
                        f"[worker {worker_rank}] Could not decode patch image: "
                        f"{patch_path}"
                    )

                if args.strict_patch_size_check:
                    patch_h, patch_w = image.shape[:2]
                    expected_patch = (
                        args.official_patch_size,
                        args.official_patch_size,
                    )
                    if (patch_h, patch_w) != expected_patch:
                        raise RuntimeError(
                            f"[worker {worker_rank}] Formal SODA-A evaluation "
                            f"expects official {args.official_patch_size}x"
                            f"{args.official_patch_size} patches, got "
                            f"{(patch_h, patch_w)} for {patch_path}."
                        )

                canvas, transform = prepare_mmrotate_style_patch(
                    image,
                    content_size=args.content_size,
                    pad_divisor=args.pad_divisor,
                    padding_value=args.padding_value,
                )

                expected_shape = (
                    args.inference_input_size,
                    args.inference_input_size,
                )
                if transform["input_shape"] != expected_shape:
                    raise RuntimeError(
                        f"[worker {worker_rank}] Official SODA-A patches must "
                        f"produce {args.inference_input_size}x"
                        f"{args.inference_input_size} inputs; got "
                        f"{transform['input_shape']} for {patch_path}."
                    )

                if not first_geometry_printed:
                    first_geometry_printed = True
                    print(
                        f"[CHECK][worker {worker_rank}][GPU {device}] geometry: "
                        f"original={transform['original_shape']}, "
                        f"resized={transform['resized_shape']}, "
                        f"input={transform['input_shape']}, "
                        f"scale=({transform['scale_x']:.6f}, "
                        f"{transform['scale_y']:.6f}), "
                        "pad=(left="
                        f"{transform['pad_left']}, top="
                        f"{transform['pad_top']}, right="
                        f"{transform['pad_right']}, bottom="
                        f"{transform['pad_bottom']})",
                        flush=True,
                    )

                batch_images.append(canvas)
                batch_transforms.append(transform)
                batch_patch_ids.append(patch_id)
                batch_paths.append(patch_path)
                batch_metas.append(meta)

            # One process owns one GPU.  Do not use DDP for offline patch
            # inference; each model replica runs independently.
            results = model.predict(
                source=batch_images,
                task="obb",
                imgsz=args.inference_input_size,
                batch=len(batch_images),
                device=device,
                conf=args.conf,
                iou=args.iou,
                max_det=args.max_det,
                stream=False,
                save=False,
                verbose=False,
            )

            if len(results) != len(batch_images):
                raise RuntimeError(
                    f"[worker {worker_rank}] Prediction result count does not "
                    f"match input count: {len(results)} != {len(batch_images)}."
                )

            for (
                patch_id,
                patch_path,
                transform,
                meta,
                result,
            ) in zip(
                batch_patch_ids,
                batch_paths,
                batch_transforms,
                batch_metas,
                results,
            ):
                if not first_result_checked:
                    first_result_checked = True
                    obb_first = getattr(result, "obb", None)
                    print(
                        f"[CHECK][worker {worker_rank}] result type: "
                        f"{type(result).__name__}",
                        flush=True,
                    )
                    print(
                        f"[CHECK][worker {worker_rank}] result.obb exists: "
                        f"{obb_first is not None}",
                        flush=True,
                    )
                    if obb_first is None:
                        raise RuntimeError(
                            f"[worker {worker_rank}] First result has no OBB "
                            "output. Predictor is not running as task='obb'."
                        )
                    if not hasattr(obb_first, "xyxyxyxy"):
                        raise RuntimeError(
                            f"[worker {worker_rank}] result.obb does not expose "
                            "xyxyxyxy."
                        )

                processed_patch_ids.append(patch_id)

                obb = getattr(result, "obb", None)
                if obb is None:
                    raise RuntimeError(
                        f"[worker {worker_rank}] OBB result missing for "
                        f"{patch_id} ({patch_path})."
                    )
                if not hasattr(obb, "xyxyxyxy"):
                    raise RuntimeError(
                        f"[worker {worker_rank}] OBB result has no xyxyxyxy for "
                        f"{patch_id} ({patch_path})."
                    )

                if len(obb) >= args.max_det:
                    saturated_patches += 1

                if len(obb) == 0:
                    continue

                polygons = (
                    obb.xyxyxyxy.detach()
                    .cpu()
                    .numpy()
                    .astype(np.float32)
                )
                scores = (
                    obb.conf.detach()
                    .cpu()
                    .numpy()
                    .astype(np.float32)
                )
                classes = (
                    obb.cls.detach()
                    .cpu()
                    .numpy()
                    .astype(np.int64)
                )

                patch_polygons = restore_polygons_to_patch(
                    polygons,
                    transform,
                )

                for poly, score, class_id in zip(
                    patch_polygons,
                    scores,
                    classes,
                ):
                    class_id = int(class_id)

                    if not 0 <= class_id < NUM_CLASSES:
                        skipped_invalid_prediction += 1
                        continue
                    if not np.isfinite(score):
                        skipped_invalid_prediction += 1
                        continue

                    original_poly = poly.copy()
                    original_poly[:, 0] += float(meta["x_start"])
                    original_poly[:, 1] += float(meta["y_start"])

                    rbbox = poly2obb_np_official(
                        original_poly,
                        min_side=args.min_obb_side,
                    )
                    if rbbox is None:
                        skipped_invalid_prediction += 1
                        continue

                    row = np.concatenate(
                        [
                            rbbox,
                            np.asarray([score], dtype=np.float32),
                        ]
                    )[None, :]

                    collector[
                        str(meta["original_id"])
                    ][class_id].append(row)
                    detections += 1

            progress.update(len(record_batch))

    finally:
        progress.close()

    assigned_patch_ids = [
        record[0] for record in assigned_records
    ]

    if processed_patch_ids != assigned_patch_ids:
        missing = sorted(
            set(assigned_patch_ids)
            - set(processed_patch_ids)
        )
        unexpected = sorted(
            set(processed_patch_ids)
            - set(assigned_patch_ids)
        )
        raise RuntimeError(
            f"[worker {worker_rank}] Processed patch sequence does not match "
            "its assigned shard. "
            f"assigned={len(assigned_patch_ids)}, "
            f"processed={len(processed_patch_ids)}, "
            f"missing_examples={missing[:10]}, "
            f"unexpected_examples={unexpected[:10]}"
        )

    serializable = serialize_worker_collector(collector)
    elapsed = time.time() - start_time

    shard_payload = {
        "schema_version": 1,
        "worker_rank": int(worker_rank),
        "device": str(device),
        "assigned_patch_ids": assigned_patch_ids,
        "processed_patch_ids": processed_patch_ids,
        "predictions": serializable,
        "stats": {
            "processed": len(processed_patch_ids),
            "detections": int(detections),
            "skipped_invalid_prediction": int(
                skipped_invalid_prediction
            ),
            "saturated_patches": int(saturated_patches),
            "elapsed_seconds": float(elapsed),
        },
    }

    tmp_path = shard_path.with_suffix(
        shard_path.suffix + ".tmp"
    )
    with tmp_path.open("wb") as file:
        pickle.dump(
            shard_payload,
            file,
            protocol=pickle.HIGHEST_PROTOCOL,
        )
    os.replace(tmp_path, shard_path)

    print(
        f"[GPU-WORKER {worker_rank}] DONE device={device}, "
        f"processed={len(processed_patch_ids)}, "
        f"detections={detections}, "
        f"invalid={skipped_invalid_prediction}, "
        f"saturated={saturated_patches}, "
        f"elapsed={elapsed:.1f}s, "
        f"shard={shard_path}",
        flush=True,
    )

    # Return only a small summary through multiprocessing IPC.
    return {
        "worker_rank": int(worker_rank),
        "device": str(device),
        "shard_path": str(shard_path),
        "processed": len(processed_patch_ids),
        "detections": int(detections),
        "skipped_invalid_prediction": int(
            skipped_invalid_prediction
        ),
        "saturated_patches": int(saturated_patches),
        "elapsed_seconds": float(elapsed),
    }


def load_and_merge_inference_shards(
    shard_summaries: list[dict[str, Any]],
    expected_patch_ids: list[str],
) -> tuple[
    dict[str, dict[int, np.ndarray]],
    dict[str, int | float],
]:
    """
    Validate worker shards and combine them in worker-rank order.

    Because the manifest was split into contiguous shards, rank-order merge
    preserves manifest traversal ordering for prediction rows.
    """
    summaries = sorted(
        shard_summaries,
        key=lambda item: int(item["worker_rank"]),
    )

    combined_lists: dict[
        str,
        dict[int, list[np.ndarray]],
    ] = defaultdict(lambda: defaultdict(list))

    all_processed: list[str] = []
    total_detections = 0
    total_invalid = 0
    total_saturated = 0
    total_worker_seconds = 0.0

    for summary in summaries:
        shard_path = Path(
            summary["shard_path"]
        ).expanduser().resolve()

        if not shard_path.is_file():
            raise FileNotFoundError(
                f"Worker shard does not exist: {shard_path}"
            )

        with shard_path.open("rb") as file:
            payload = pickle.load(file)

        rank = int(payload.get("worker_rank", -1))
        if rank != int(summary["worker_rank"]):
            raise RuntimeError(
                "Worker shard rank mismatch: "
                f"summary={summary['worker_rank']}, payload={rank}"
            )

        assigned = list(payload.get("assigned_patch_ids", []))
        processed = list(payload.get("processed_patch_ids", []))

        if processed != assigned:
            raise RuntimeError(
                f"Worker {rank} shard has inconsistent assigned/processed "
                f"patches: assigned={len(assigned)}, processed={len(processed)}."
            )

        all_processed.extend(processed)

        stats = payload.get("stats", {})
        total_detections += int(stats.get("detections", 0))
        total_invalid += int(
            stats.get("skipped_invalid_prediction", 0)
        )
        total_saturated += int(
            stats.get("saturated_patches", 0)
        )
        total_worker_seconds += float(
            stats.get("elapsed_seconds", 0.0)
        )

        predictions = payload.get("predictions")
        if not isinstance(predictions, dict):
            raise RuntimeError(
                f"Worker {rank} shard has invalid predictions payload."
            )

        for original_id, class_map in predictions.items():
            if not isinstance(class_map, dict):
                raise RuntimeError(
                    f"Worker {rank} class map is invalid for "
                    f"original_id={original_id}."
                )

            for class_id, array in class_map.items():
                class_id = int(class_id)
                if not 0 <= class_id < NUM_CLASSES:
                    raise RuntimeError(
                        f"Worker {rank} emitted invalid class_id={class_id}."
                    )

                values = np.asarray(
                    array,
                    dtype=np.float32,
                ).reshape(-1, 6)

                if not np.isfinite(values).all():
                    raise RuntimeError(
                        f"Worker {rank} emitted non-finite detections for "
                        f"{original_id}, class_id={class_id}."
                    )

                if len(values):
                    combined_lists[
                        str(original_id)
                    ][class_id].append(values)

    expected_set = set(expected_patch_ids)
    processed_set = set(all_processed)

    duplicate_count = (
        len(all_processed) - len(processed_set)
    )
    missing = sorted(expected_set - processed_set)
    unexpected = sorted(processed_set - expected_set)

    if (
        len(all_processed) != len(expected_patch_ids)
        or duplicate_count != 0
        or missing
        or unexpected
    ):
        raise RuntimeError(
            "Multi-GPU patch completeness check failed.\n"
            f"Expected:    {len(expected_patch_ids)}\n"
            f"Processed:   {len(all_processed)}\n"
            f"Unique:      {len(processed_set)}\n"
            f"Duplicates:  {duplicate_count}\n"
            f"Missing:     {len(missing)} examples={missing[:20]}\n"
            f"Unexpected:  {len(unexpected)} examples={unexpected[:20]}"
        )

    # Stronger ordering check: rank-ordered contiguous shards must reproduce
    # the exact manifest order.
    if all_processed != expected_patch_ids:
        mismatch_index = next(
            (
                index
                for index, (got, expected) in enumerate(
                    zip(all_processed, expected_patch_ids)
                )
                if got != expected
            ),
            None,
        )
        raise RuntimeError(
            "Multi-GPU shard merge does not preserve manifest order. "
            f"First mismatch index={mismatch_index}."
        )

    combined: dict[str, dict[int, np.ndarray]] = {}
    for original_id, class_map in combined_lists.items():
        combined[original_id] = {}
        for class_id, arrays in class_map.items():
            combined[original_id][class_id] = (
                np.concatenate(arrays, axis=0).astype(
                    np.float32,
                    copy=False,
                )
                if arrays
                else np.zeros((0, 6), dtype=np.float32)
            )

    totals: dict[str, int | float] = {
        "processed": len(all_processed),
        "unique_processed": len(processed_set),
        "duplicate_patches": int(duplicate_count),
        "missing_patches": len(missing),
        "unexpected_patches": len(unexpected),
        "detections": int(total_detections),
        "skipped_invalid_prediction": int(total_invalid),
        "saturated_patches": int(total_saturated),
        "sum_worker_seconds": float(total_worker_seconds),
    }

    return combined, totals


def run_inference(
    args: argparse.Namespace,
    patch_cache: Path,
    expected_metadata: dict[str, Any],
) -> None:
    """
    Run formal SODA-A patch inference with independent multi-GPU workers.
    """
    model_path = Path(args.model).expanduser().resolve()
    patch_dir = Path(args.patch_dir).expanduser().resolve()
    manifest_path = Path(args.manifest).expanduser().resolve()

    if not model_path.is_file():
        raise FileNotFoundError(
            f"Model does not exist: {model_path}"
        )

    manifest = load_test_manifest(manifest_path)
    patch_index = build_patch_image_index(
        patch_dir,
        manifest,
    )
    ordered_patch_ids = list(manifest)

    # Validate the official polygon converter before spending GPU hours.
    validate_official_poly2obb_converter()

    devices = list(args.inference_devices)
    num_workers = len(devices)

    if num_workers > len(ordered_patch_ids):
        raise ValueError(
            f"More inference workers ({num_workers}) than patches "
            f"({len(ordered_patch_ids)})."
        )

    patch_id_shards = split_contiguous(
        ordered_patch_ids,
        num_workers,
    )

    # Build compact records once in the parent.  Each worker receives only its
    # own contiguous shard.
    record_shards: list[
        list[tuple[str, str, dict[str, Any]]]
    ] = []

    for patch_ids in patch_id_shards:
        records = [
            (
                patch_id,
                str(patch_index[patch_id]),
                dict(manifest[patch_id]),
            )
            for patch_id in patch_ids
        ]
        record_shards.append(records)

    assigned_flat = [
        patch_id
        for shard in patch_id_shards
        for patch_id in shard
    ]

    if assigned_flat != ordered_patch_ids:
        raise RuntimeError(
            "Internal multi-GPU shard assignment does not preserve "
            "the manifest order."
        )

    if len(set(assigned_flat)) != len(assigned_flat):
        raise RuntimeError(
            "Internal multi-GPU shard assignment contains duplicate patches."
        )

    print("[MULTI-GPU] inference configuration")
    print(f"[MULTI-GPU] devices:          {devices}")
    print(f"[MULTI-GPU] workers:          {num_workers}")
    print(f"[MULTI-GPU] batch/GPU:        {args.batch_per_gpu}")
    print(
        "[MULTI-GPU] max concurrent:   "
        f"{num_workers * args.batch_per_gpu} patches"
    )

    for rank, (device, shard) in enumerate(
        zip(devices, patch_id_shards)
    ):
        first_id = shard[0] if shard else "<empty>"
        last_id = shard[-1] if shard else "<empty>"
        print(
            f"[MULTI-GPU] rank{rank}: GPU {device}, "
            f"patches={len(shard)}, "
            f"range=[{first_id} ... {last_id}]"
        )

    shard_dir = (
        patch_cache.parent
        / "_multigpu_inference_shards"
    )
    shard_dir.mkdir(
        parents=True,
        exist_ok=True,
    )

    worker_args = vars(args).copy()
    worker_tasks = []

    for rank, (
        device,
        assigned_records,
    ) in enumerate(
        zip(devices, record_shards)
    ):
        shard_path = (
            shard_dir
            / f"patch_predictions_rank{rank}_gpu{device}.pkl"
        )
        worker_tasks.append(
            (
                rank,
                str(device),
                assigned_records,
                worker_args,
                str(shard_path),
            )
        )

    wall_start = time.time()

    # CUDA multiprocessing must use spawn, not fork.
    ctx = mp.get_context("spawn")

    with ctx.Pool(
        processes=num_workers,
        maxtasksperchild=1,
    ) as pool:
        shard_summaries = pool.starmap(
            inference_worker,
            worker_tasks,
        )

    predictions, totals = (
        load_and_merge_inference_shards(
            shard_summaries,
            expected_patch_ids=ordered_patch_ids,
        )
    )

    wall_elapsed = time.time() - wall_start

    payload = {
        "metadata": expected_metadata,
        "predictions": predictions,
        "multigpu_runtime": {
            "devices": devices,
            "workers": num_workers,
            "batch_per_gpu": int(
                args.batch_per_gpu
            ),
            "wall_elapsed_seconds": float(
                wall_elapsed
            ),
            **totals,
            "worker_summaries": sorted(
                shard_summaries,
                key=lambda item: int(
                    item["worker_rank"]
                ),
            ),
        },
    }

    tmp_cache = patch_cache.with_suffix(
        patch_cache.suffix + ".tmp"
    )
    with tmp_cache.open("wb") as file:
        pickle.dump(
            payload,
            file,
            protocol=pickle.HIGHEST_PROTOCOL,
        )
    os.replace(tmp_cache, patch_cache)

    print("[MULTI-GPU] completeness check: PASS")
    print(
        f"[INFER] processed patches:           "
        f"{totals['processed']}"
    )
    print(
        f"[INFER] unique processed patches:    "
        f"{totals['unique_processed']}"
    )
    print(
        f"[INFER] duplicate patches:           "
        f"{totals['duplicate_patches']}"
    )
    print(
        f"[INFER] missing patches:             "
        f"{totals['missing_patches']}"
    )
    print(
        f"[INFER] mapped detections:           "
        f"{totals['detections']}"
    )
    print(
        f"[INFER] invalid predictions skipped: "
        f"{totals['skipped_invalid_prediction']}"
    )
    print(
        f"[INFER] max_det-saturated patches:   "
        f"{totals['saturated_patches']}"
    )
    print(
        f"[INFER] multi-GPU wall time:         "
        f"{wall_elapsed:.1f} s"
    )
    print(
        f"[INFER] sum worker GPU time:         "
        f"{totals['sum_worker_seconds']:.1f} s"
    )
    print(f"[INFER] shard directory:             {shard_dir}")
    print(f"[INFER] cache:                       {patch_cache}")


def _load_importable_module_from_file(path: Path):
    path = path.expanduser().resolve()
    module_name = path.stem
    module_dir = str(path.parent)

    if module_dir not in sys.path:
        sys.path.insert(0, module_dir)
    importlib.invalidate_caches()

    existing = sys.modules.get(module_name)
    if existing is not None:
        existing_file = getattr(existing, "__file__", None)
        try:
            same_file = (
                existing_file is not None
                and Path(existing_file).expanduser().resolve() == path
            )
        except (OSError, RuntimeError, TypeError):
            same_file = False

        if same_file:
            return existing
        del sys.modules[module_name]

    spec = importlib.util.spec_from_file_location(module_name, str(path))
    if spec is None or spec.loader is None:
        raise ImportError(f"Unable to create import spec for: {path}")

    module = importlib.util.module_from_spec(spec)
    sys.modules[module_name] = module
    try:
        spec.loader.exec_module(module)
    except Exception:
        sys.modules.pop(module_name, None)
        raise

    return module


